#!/usr/bin/env python3
"""Worktree delivery evidence gate. This does not implement or simulate product tests.

Evidence stays in repository temp/. Missing/skipped cases and absent platform/manual
proof are failures. Baseline failures remain visible; only NEW failures block the
full regression comparison. Reports must be generated by Gradle on this source tree.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import os
from pathlib import Path
import platform
import re
import shutil
import subprocess
import sys
import time
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[1]
ASSETS = ROOT / "scripts/worktree-acceptance"
MANIFEST = ASSETS / "acceptance.json"
VERSION = "WT-2026-11-02.1"


def require(condition, message):
    if not condition:
        raise ValueError(message)


def read_json(path):
    return json.loads(path.read_text(encoding="utf-8"))


def write_json(path, value):
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_name(path.name + ".partial")
    temporary.write_text(json.dumps(value, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    temporary.replace(path)


def digest(path):
    result = hashlib.sha256()
    with path.open("rb") as stream:
        for chunk in iter(lambda: stream.read(1024 * 1024), b""):
            result.update(chunk)
    return result.hexdigest()


def fingerprint():
    names = subprocess.check_output(
        ["git", "ls-files", "-z", "--cached", "--others", "--exclude-standard"], cwd=ROOT
    ).split(b"\0")
    value = hashlib.sha256()
    for raw in sorted(set(names) - {b""}):
        name = os.fsdecode(raw)
        path = ROOT / name
        value.update(raw + b"\0")
        if path.is_symlink():
            value.update(b"LINK\0" + os.fsencode(os.readlink(path)))
        elif path.is_file():
            value.update(b"FILE\0" + digest(path).encode())
            value.update(str(path.stat().st_mode & 0o777).encode())
        else:
            value.update(b"MISSING")
    return value.hexdigest()


def host_platform():
    return {"Darwin": "macos", "Linux": "linux", "Windows": "windows"}.get(platform.system(), "unknown")


def inside_evidence(directory, relative):
    path = (directory / relative).resolve()
    require(path.is_relative_to(directory.resolve()), f"Evidence path escapes directory: {relative}")
    return path


def cases_in(paths):
    cases = {}
    for path in paths:
        root = ET.parse(path).getroot()
        for case in root.iter("testcase"):
            name = re.sub(r"\[jvm\]$", "", case.get("name", ""))
            key = case.get("classname", "") + "." + name
            state = "FAIL" if case.find("failure") is not None or case.find("error") is not None else (
                "SKIP" if case.find("skipped") is not None else "PASS"
            )
            require(key not in cases, f"Duplicate test evidence: {key}")
            cases[key] = state
    return cases


def suite_errors(manifest, cases, native=None):
    errors = []
    for suite in manifest["suites"]:
        if suite["platform"] != (native or "any"):
            continue
        for method in suite["tests"]:
            key = suite["className"] + "." + method
            state = cases.get(key) if key in cases else cases.get(key + "()")
            if state != "PASS":
                errors.append(f"{key}: {state or 'MISSING'}")
    return errors


def run_gradle(arguments, log, environment=None):
    env = os.environ.copy()
    env.update(environment or {})
    with log.open("wb") as output:
        process = subprocess.run([str(ROOT / "gradlew"), *arguments, "--console=plain"],
                                 cwd=ROOT, env=env, stdout=output, stderr=subprocess.STDOUT)
    print(f"Gradle exit={process.returncode}; log={log.relative_to(ROOT)}")
    return process.returncode


def copy_reports(directory, modules):
    reports = []
    for module in modules:
        source = ROOT / ("core" if module == "core" else "app/shared") / "build/test-results/jvmTest"
        target = directory / "reports" / module
        target.mkdir(parents=True, exist_ok=True)
        for old in target.glob("*.xml"):
            old.unlink()
        current = sorted(source.glob("TEST-*.xml"))
        require(current, f"Missing Gradle XML reports for {module}")
        for path in current:
            destination = target / path.name
            shutil.copy2(path, destination)
            reports.append(destination)
    return reports


def make_receipt(directory, reports, source, **extra):
    return dict(specVersion=VERSION, sourceFingerprint=source, host=platform.node(),
                platform=host_platform(), recordedAt=time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
                reports=[dict(path=str(path.relative_to(directory)), sha256=digest(path)) for path in reports],
                **extra)


def checked_reports(directory, receipt, source):
    require(receipt.get("specVersion") == VERSION, "Receipt spec version mismatch")
    require(receipt.get("sourceFingerprint") == source, "Receipt does not match current source fingerprint")
    paths = []
    for item in receipt.get("reports", []):
        path = inside_evidence(directory, item["path"])
        require(path.is_file() and digest(path) == item["sha256"], f"Report checksum mismatch: {path}")
        paths.append(path)
    require(paths, "Receipt has no test reports")
    return cases_in(paths)


def manifest_check(manifest):
    require(manifest["specVersion"] == VERSION, "Manifest version mismatch")
    manual = read_json(ASSETS / "manual-template.json")
    require(manual["specVersion"] == VERSION, "Manual template version mismatch")
    require([(item["id"], item["requirement"]) for item in manual["scenarios"]] ==
            [(item["id"], item["requirement"]) for item in manifest["manualScenarios"]],
            "Manual template scenarios differ from the acceptance manifest")
    keys = []
    for suite in manifest["suites"]:
        require(suite["platform"] in ("any", "macos", "linux"), "Unknown suite platform")
        require(suite["module"] in ("core", "shared"), "Unknown suite module")
        require(suite["tests"], f"Empty suite {suite['className']}")
        keys.extend(suite["className"] + "." + method for method in suite["tests"])
    require(len(keys) == len(set(keys)), "Duplicate required test cases")
    print(f"Manifest valid: {len(manifest['suites'])} suites, {len(keys)} required cases")


def record_baseline(directory, source):
    target = directory / "baseline"
    target.mkdir(parents=True, exist_ok=True)
    require(not (target / "receipt.json").exists(), "Baseline already recorded; do not overwrite the pre-implementation baseline")
    code = run_gradle([":core:jvmTest", ":app:shared:jvmTest", "--continue"], target / "gradle.log")
    log = (target / "gradle.log").read_text(errors="replace")
    require(not re.search(r"> Task .*compile.* FAILED", log), "Compilation failed; not a usable test baseline")
    reports = copy_reports(target, ["core", "shared"])
    cases = cases_in(reports)
    require(cases and (code == 0 or "tests completed" in log), "Incomplete baseline run")
    require(fingerprint() == source, "Sources changed while recording baseline")
    write_json(target / "receipt.json", make_receipt(target, reports, source,
               startingHead=subprocess.check_output(["git", "rev-parse", "HEAD"], cwd=ROOT).decode().strip(),
               failedCases=sorted(key for key, state in cases.items() if state == "FAIL"), exitCode=code))
    print("Baseline recorded with existing failures visible; this is not delivery acceptance.")


def regular_run(directory, manifest, source):
    baseline_path = directory / "baseline/receipt.json"
    require(baseline_path.is_file(), "Record --baseline before implementing; do not invent a baseline afterward")
    baseline = read_json(baseline_path)
    # Validate baseline report integrity, but its source is intentionally the old tree.
    checked_reports(baseline_path.parent, baseline, baseline["sourceFingerprint"])
    target = directory / "regular"
    target.mkdir(parents=True, exist_ok=True)
    code = run_gradle([":core:jvmTest", ":app:shared:jvmTest", "--continue"], target / "tests.log")
    reports = copy_reports(target, ["core", "shared"])
    cases = cases_in(reports)
    new_failures = sorted(key for key, value in cases.items() if value == "FAIL" and key not in baseline["failedCases"])
    log = (target / "tests.log").read_text(errors="replace")
    errors = suite_errors(manifest, cases)
    if code and "tests completed" not in log:
        errors.append("Regression run did not complete")
    if re.search(r"> Task .*compile.* FAILED", log):
        errors.append("Regression compilation failed")
    errors.extend("New regression: " + key for key in new_failures)
    compilations = {"jvm": ":app:shared:compileKotlinJvm", "android": ":app:shared:compileAndroidMain",
                    "wasmJs": ":app:shared:compileKotlinWasmJs"}
    if host_platform() == "macos":
        compilations["iosSimulatorArm64"] = ":app:shared:compileKotlinIosSimulatorArm64"
    compile_code = run_gradle(list(compilations.values()) + ["--continue"], target / "compile.log")
    if compile_code:
        errors.append("Platform compilation failed")
    require(fingerprint() == source, "Sources changed while testing")
    write_json(target / "receipt.json", make_receipt(target, reports, source, errors=errors,
               compilations=list(compilations) if compile_code == 0 else [],
               existingFailures=sorted(key for key, value in cases.items() if value == "FAIL"),
               testExitCode=code, compileExitCode=compile_code))
    require(not errors, "\n".join(errors))
    print("Regular tests/compilation recorded. Native and manual evidence still required.")


def native_run(directory, manifest, source, native):
    require(host_platform() == native, f"Native {native} verification cannot run on {host_platform()}")
    target = directory / "native" / native
    target.mkdir(parents=True, exist_ok=True)
    suite = next(item for item in manifest["suites"] if item["platform"] == native)
    flag = "MEDERI_REQUIRE_MACOS_SANDBOX" if native == "macos" else "MEDERI_REQUIRE_LINUX_SANDBOX"
    code = run_gradle([":core:jvmTest", "--tests", suite["className"], "--rerun-tasks"],
                      target / "gradle.log", {flag: "1"})
    reports = copy_reports(target, ["core"])
    errors = suite_errors(manifest, cases_in(reports), native)
    if code:
        errors.append(f"Native Gradle exit={code}")
    compilations = []
    if native == "macos":
        result = run_gradle([":app:shared:compileKotlinIosSimulatorArm64"], target / "ios-compile.log")
        if result:
            errors.append("iOS compilation failed")
        else:
            compilations.append("iosSimulatorArm64")
    require(fingerprint() == source, "Sources changed while running native tests")
    write_json(target / "receipt.json", make_receipt(target, reports, source,
               requiredFlag=flag, requiredMode=True, errors=errors, compilations=compilations))
    require(not errors, "\n".join(errors))


def final_check(directory, manifest, source):
    errors = []
    compiled = set()
    regular_path = directory / "regular/receipt.json"
    require(regular_path.is_file(), "Missing regular receipt; run --run")
    receipt = read_json(regular_path)
    cases = checked_reports(regular_path.parent, receipt, source)
    baseline_path = directory / "baseline/receipt.json"
    require(baseline_path.is_file(), "Missing pre-implementation baseline receipt")
    baseline = read_json(baseline_path)
    baseline_cases = checked_reports(baseline_path.parent, baseline, baseline["sourceFingerprint"])
    baseline_failures = {key for key, state in baseline_cases.items() if state == "FAIL"}
    require(baseline_failures == set(baseline["failedCases"]), "Baseline failure list does not match reports")
    errors.extend("New regression: " + key for key, state in cases.items()
                  if state == "FAIL" and key not in baseline_failures)
    errors.extend(receipt.get("errors", []))
    errors.extend(suite_errors(manifest, cases))
    compiled.update(receipt.get("compilations", []))
    for native in manifest["requiredNativePlatforms"]:
        path = directory / "native" / native / "receipt.json"
        if not path.is_file():
            errors.append(f"Missing native {native} evidence")
            continue
        proof = read_json(path)
        require(proof.get("platform") == native and proof.get("requiredMode") is True,
                f"Invalid native {native} receipt")
        cases = checked_reports(path.parent, proof, source)
        errors.extend(proof.get("errors", []))
        errors.extend(suite_errors(manifest, cases, native))
        compiled.update(proof.get("compilations", []))
    errors.extend(f"Missing compilation: {item}" for item in manifest["requiredCompilations"] if item not in compiled)
    manual_path = directory / "manual.json"
    if not manual_path.is_file():
        errors.append("Missing desktop/mobile/Codex manual evidence")
    else:
        manual = read_json(manual_path)
        require(manual.get("specVersion") == VERSION and manual.get("sourceFingerprint") == source,
                "Manual evidence does not match current source/spec")
        require(manual.get("unresolvedDifferences") == [], "Manual parity differences remain unresolved")
        require(all(manual.get(key) for key in ("desktopAppVersion", "codexAppVersion", "mobileClient", "verifiedAt")),
                "Manual evidence must identify actual apps, mobile client and verification time")
        scenarios = {item["id"]: item for item in manual.get("scenarios", [])}
        for expected in manifest["manualScenarios"]:
            item = scenarios.get(expected["id"], {})
            require(item.get("status") == "PASS" and len(item.get("observed", "").strip()) >= 20,
                    "Missing concrete observation for " + expected["id"])
            require(item.get("artifacts"), "Missing artifacts for " + expected["id"])
            for relative in item["artifacts"]:
                path = inside_evidence(directory, relative)
                require(path.is_file() and path.stat().st_size > 0, f"Missing manual artifact {relative}")
    delivery_path = directory / "delivery.md"
    if not delivery_path.is_file() or not delivery_path.read_text(encoding="utf-8").strip():
        errors.append("Missing nonempty delivery.md in the evidence directory")
    require(not errors, "\n".join(errors))
    print("PASS: required behavior, regressions, platforms and manual parity evidence are complete.")
    print("Retained baseline failures:", receipt.get("existingFailures", []))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    modes = parser.add_mutually_exclusive_group()
    modes.add_argument("--manifest-only", "--docs-only", action="store_true")
    modes.add_argument("--baseline", action="store_true")
    modes.add_argument("--run", action="store_true")
    modes.add_argument("--native", choices=["macos", "linux"])
    parser.add_argument("--evidence-dir", default="temp/worktree-evidence/delivery")
    args = parser.parse_args()
    manifest = read_json(MANIFEST)
    manifest_check(manifest)
    if args.manifest_only:
        return
    directory = (ROOT / args.evidence_dir).resolve()
    allowed = (ROOT / "temp/worktree-evidence").resolve()
    require(directory.is_relative_to(allowed), "Evidence directory must be inside repository temp/worktree-evidence")
    directory.mkdir(parents=True, exist_ok=True)
    source = fingerprint()
    print("Source fingerprint:", source)
    if args.baseline:
        record_baseline(directory, source)
    elif args.run:
        regular_run(directory, manifest, source)
    elif args.native:
        native_run(directory, manifest, source, args.native)
    else:
        final_check(directory, manifest, source)


if __name__ == "__main__":
    try:
        main()
    except (ValueError, OSError, KeyError, ET.ParseError, json.JSONDecodeError) as failure:
        print("NOT ACCEPTED:", failure, file=sys.stderr)
        sys.exit(1)
